// Package goldentest implements the v0.2.2 golden-vector harness that
// enforces semantic API stability: existing
// identifiers called with no new options must reproduce v0.2.2 results,
// except for changes listed in a per-module allowlist.
//
// Expected results are generated only from the v0.2.2 tag, by
// tools/golden-regen.sh (make golden-regen). Running a golden test with
// -golden.update outside that script fails, so vectors can't drift to
// match new behavior by accident.
package goldentest

import (
	"encoding/hex"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"testing"
)

// Version is the release the vectors are captured from.
const Version = "v0.2.2"

// regenEnv is set by tools/golden-regen.sh when it runs inside a v0.2.2
// worktree.
const regenEnv = "CORECBOR_GOLDEN_FROM"

var update = flag.Bool("golden.update", false,
	"regenerate golden vectors (only valid from the "+Version+" tag via make golden-regen)")

// Case is one golden vector. Run must be deterministic; it returns the
// observed result as a string (see Hex, Err, Str).
type Case struct {
	ID  string
	Run func() string
}

// Vector is the on-disk form of one case.
type Vector struct {
	ID     string `json:"id"`
	Result string `json:"result"`
}

type file struct {
	GeneratedFrom string   `json:"generated_from"`
	Note          string   `json:"note"`
	Vectors       []Vector `json:"vectors"`
}

// Check runs cases and compares them to the vectors in path. changes maps
// vector IDs whose results are allowed to differ from v0.2.2 to the
// reason they change. Allowlisted mismatches are logged; any
// other mismatch, missing vector, or stale allowlist entry fails.
func Check(t *testing.T, path string, cases []Case, changes map[string]string) {
	t.Helper()
	seen := make(map[string]bool, len(cases))
	for _, c := range cases {
		if seen[c.ID] {
			t.Fatalf("duplicate golden case id %q", c.ID)
		}
		seen[c.ID] = true
	}

	if *update {
		if os.Getenv(regenEnv) != Version {
			t.Fatalf("-golden.update is only valid inside a %s worktree; run `make golden-regen`", Version)
		}
		write(t, path, cases)
		return
	}

	want := read(t, path)
	for id := range changes {
		if !seen[id] {
			t.Errorf("allowlist entry %q has no golden case; remove it", id)
		}
	}
	for _, c := range cases {
		exp, ok := want[c.ID]
		if !ok {
			t.Errorf("%s: no %s vector; regenerate with `make golden-regen`", c.ID, Version)
			continue
		}
		delete(want, c.ID)
		got := run(c)
		if got == exp {
			if reason, ok := changes[c.ID]; ok {
				t.Logf("%s: allowlisted (%s) but unchanged from %s", c.ID, reason, Version)
			}
			continue
		}
		if reason, ok := changes[c.ID]; ok {
			t.Logf("%s: changed from %s (allowlisted: %s)\n  %s: %s\n  now:    %s", c.ID, Version, reason, Version, exp, got)
			continue
		}
		t.Errorf("%s: differs from %s and is not allowlisted\n  %s: %s\n  now:    %s", c.ID, Version, Version, exp, got)
	}
	ids := make([]string, 0, len(want))
	for id := range want {
		ids = append(ids, id)
	}
	sort.Strings(ids)
	for _, id := range ids {
		t.Errorf("%s: %s vector has no case (cases may not be removed)", id, Version)
	}
}

func run(c Case) (out string) {
	defer func() {
		if r := recover(); r != nil {
			out = "panic"
		}
	}()
	return c.Run()
}

func read(t *testing.T, path string) map[string]string {
	t.Helper()
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatalf("read golden vectors: %v", err)
	}
	var f file
	if err := json.Unmarshal(data, &f); err != nil {
		t.Fatalf("parse %s: %v", path, err)
	}
	if f.GeneratedFrom != Version {
		t.Fatalf("%s generated from %q, want %q", path, f.GeneratedFrom, Version)
	}
	m := make(map[string]string, len(f.Vectors))
	for _, v := range f.Vectors {
		m[v.ID] = v.Result
	}
	return m
}

func write(t *testing.T, path string, cases []Case) {
	t.Helper()
	f := file{
		GeneratedFrom: Version,
		Note:          "Generated by `make golden-regen` from the " + Version + " tag. Do not edit by hand.",
	}
	for _, c := range cases {
		f.Vectors = append(f.Vectors, Vector{ID: c.ID, Result: run(c)})
	}
	data, err := json.MarshalIndent(f, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, append(data, '\n'), 0o644); err != nil {
		t.Fatal(err)
	}
}

// Sentinel names an error sentinel for result encoding.
type Sentinel struct {
	Name string
	Err  error
}

// Err encodes err as "err:" followed by the sorted names of every
// sentinel it matches with errors.Is, or "err:unclassified". Error
// message text is deliberately not recorded: it isn't API.
func Err(err error, sentinels []Sentinel) string {
	var names []string
	for _, s := range sentinels {
		if errors.Is(err, s.Err) {
			names = append(names, s.Name)
		}
	}
	if len(names) == 0 {
		return "err:unclassified"
	}
	sort.Strings(names)
	return "err:" + strings.Join(names, ",")
}

// Hex encodes b as "hex:<lowercase hex>", or the error per Err.
func Hex(b []byte, err error, sentinels []Sentinel) string {
	if err != nil {
		return Err(err, sentinels)
	}
	return "hex:" + hex.EncodeToString(b)
}

// Str encodes s as "ok:<s>", or the error per Err.
func Str(s string, err error, sentinels []Sentinel) string {
	if err != nil {
		return Err(err, sentinels)
	}
	return "ok:" + s
}

// OK encodes a nil error as "ok", or the error per Err.
func OK(err error, sentinels []Sentinel) string {
	return Str("", err, sentinels)
}

// MustHex decodes a hex literal used as test input.
func MustHex(s string) []byte {
	b, err := hex.DecodeString(strings.ReplaceAll(s, " ", ""))
	if err != nil {
		panic(fmt.Sprintf("goldentest: bad hex %q: %v", s, err))
	}
	return b
}
